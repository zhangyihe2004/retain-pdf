from __future__ import annotations

from retainpdf_pipeline.render.layout.payload.fit_common import FLOW_TEXT_MIN_FONT_SIZE_PT


def glyph_edge_fit_helpers() -> list[str]:
    """The same outer glyph bounds for flowing text and titles."""
    return [
        '#let pdftr_glyph_block(source, text_size, weight: "regular", leading: 0.66em, width: none, first_line_indent: 0pt, justify: false, plain: false) = {',
        '  let content(value) = if plain { text(value) } else { cmarker.render(value, math: mitex) }',
        '  let probe(top, bottom) = block[#{',
        '    set text(size: text_size, weight: weight, top-edge: top, bottom-edge: bottom)',
        r'    content(source.replace("\n", " "))',
        '  }]',
        '  let base = measure(probe("cap-height", "baseline")).height',
        '  let top = calc.max(0pt, measure(probe("ascender", "baseline")).height - base, measure(probe("bounds", "baseline")).height - base)',
        '  let bottom = calc.max(0pt, measure(probe("cap-height", "descender")).height - base, measure(probe("cap-height", "bounds")).height - base)',
        '  pad(top: top, bottom: bottom, block(width: if width == none { auto } else { width })[#{',
        '    set text(size: text_size, weight: weight)',
        '    set par(leading: leading, justify: justify)',
        '    if first_line_indent > 0pt { h(first_line_indent) }',
        '    content(source)',
        '  }])',
        '}',
    ]


def preferred_width_helpers() -> list[str]:
    """Choose actual width only after typography has been fitted to capacity."""
    return [
        '#let pdftr_preferred_width(preferred, available, fits) = {',
        '  if preferred == none or preferred <= 0pt or preferred >= available { available }',
        '  else if fits(preferred) { preferred } else if not fits(available) { available } else {',
        '    available - pdftr_fit_size(0pt, available - preferred, 0.25pt, reduction => fits(available - reduction))',
        '  }',
        '}',
    ]


def flow_text_fit_helpers() -> list[str]:
    """One measured fit for ordinary text in both Typst output paths."""
    return [
        '#let pdftr_fit_flow_text(source, max_size: 10pt, max_leading: 0.66em, min_leading: 0.54em, fit_height: none, preferred_width: none, weight: "regular", first_line_indent: 0pt, justify: false, plain: false, block_id: "") = {',
        "  layout(size => {",
        "    let allowed-height = if fit_height == none { size.height } else { calc.min(size.height, fit_height) }",
        '    assert(size.width > 0pt and allowed-height > 0pt, message: "PDF text has no positive content area: " + block_id)',
        '    let render(text_size, leading, width) = pdftr_glyph_block(source, text_size, weight: weight, leading: leading, width: width, first_line_indent: first_line_indent, justify: justify, plain: plain)',
        '    let fits-width(text_size, leading, width) = {',
        # Finite-width measure reports the frame, even for overflowing words.
        # Probe rendered text (including inline styles), not Markdown syntax.
        # CJK keeps its native wrapping; western runs may also wrap/hyphenate.
        '      let probe = {',
        r'        show regex("[^\s\p{Han}\p{Hiragana}\p{Katakana}\p{Hangul}\u{200b}]+") : it => context {',
        '          let fits-run(body) = {',
        '            let natural = measure(body)',
        '            natural.width <= width or measure(width: width, body).height > natural.height',
        '          }',
        # Only inspect overwide runs. A wrapping prefix/suffix must not hide
        # an unbreakable, punctuated word group (for example a dotted address).
        '          if measure(it).width > width {',
        r'            let words = it.text.matches(regex("[\p{L}\p{N}\p{M}]+"))',
        '            let words-fit = words.enumerate().all(((index, first)) => {',
        '              words.slice(index).all(last => fits-run(text(it.text.slice(first.start, last.end))))',
        '            })',
        '            if not fits-run(it) or not words-fit { v(allowed-height + text_size) }',
        '          }',
        '          it',
        '        }',
        '        render(text_size, leading, width)',
        '      }',
        # Show-rule probing can change wrapping. Height must also fit the exact
        # content that will be emitted, not just its horizontal-check probe.
        '      measure(width: width, render(text_size, leading, width)).height <= allowed-height and measure(width: width, probe).height <= allowed-height',
        '    }',
        '    let fits(text_size, leading) = fits-width(text_size, leading, size.width)',
        '    let emit(text_size, leading) = {',
        '      let width = pdftr_preferred_width(preferred_width, size.width, width => fits-width(text_size, leading, width))',
        '      render(text_size, leading, width)',
        '    }',
        "    if fits(max_size, max_leading) {",
        "      emit(max_size, max_leading)",
        "    } else {",
        "      let leading-floor = calc.min(min_leading, max_leading)",
        f"      let font-floor = calc.min(max_size, {FLOW_TEXT_MIN_FONT_SIZE_PT}pt)",
        # Keep fitting best-effort: an undersized frame must not abort the PDF.
        "      let chosen-size = if fits(max_size, leading-floor) { max_size } else {",
        "        pdftr_fit_size(font-floor, max_size, 0.08pt, size_pt => fits(size_pt, leading-floor))",
        "      }",
        "      let chosen-leading = if fits(chosen-size, max_leading) { max_leading } else {",
        "        pdftr_fit_size(leading-floor, max_leading, 0.01em, leading => fits(chosen-size, leading))",
        "      }",
        "      emit(chosen-size, chosen-leading)",
        "    }",
        "  })",
        "}",
    ]


def single_line_fit_helpers() -> list[str]:
    return [
        '#let pdftr_fit_single_line_markdown(markdown, max_size: 10pt, min_size: 9pt, fit_width: none, fit_height: none, preferred_width: none, weight: "regular", justify: false, eps: 0.08pt) = {',
        "  layout(size => {",
        "    let available-width = if fit_width == none { size.width } else { calc.min(size.width, fit_width) }",
        "    let allowed-height = if fit_height == none { size.height } else { calc.min(size.height, fit_height) }",
        '    let render(text_size) = pdftr_glyph_block(markdown, text_size, weight: weight, leading: 1em, justify: justify)',
        "    let fits-width(text_size, width) = {",
        "      let measured = measure(render(text_size))",
        "      measured.width <= width and measured.height <= allowed-height",
        "    }",
        "    let fits(text_size) = fits-width(text_size, available-width)",
        "    let chosen-size = if fits(max_size) {",
        "      max_size",
        "    } else {",
        "      if not fits(min_size) {",
        "        let emergency-min-size = calc.max(4.2pt, min_size * 0.55)",
        "        pdftr_fit_size(emergency-min-size, min_size, eps, size_pt => fits(size_pt))",
        "      } else {",
        "        pdftr_fit_size(min_size, max_size, eps, size_pt => fits(size_pt))",
        "      }",
        "    }",
        '    let final-width = pdftr_preferred_width(preferred_width, available-width, width => fits-width(chosen-size, width))',
        '    box(width: final-width, height: allowed-height, inset: 0pt, clip: false)[#render(chosen-size)]',
        "  })",
        "}",
    ]


def page_spec_fit_helpers() -> list[str]:
    return [
        *glyph_edge_fit_helpers(),
        "#let pdftr_fit_size(lo, hi, eps, fits) = {",
        "  if hi - lo <= eps {",
        "    lo",
        "  } else {",
        "    let mid = lo + (hi - lo) / 2",
        "    if fits(mid) {",
        "      pdftr_fit_size(mid, hi, eps, fits)",
        "    } else {",
        "      pdftr_fit_size(lo, mid, eps, fits)",
        "    }",
        "  }",
        "}",
        *preferred_width_helpers(),
        *single_line_fit_helpers(),
        "#let pdftr_fit_markdown(markdown, max_size: 10pt, min_size: 9pt, max_leading: 0.66em, min_leading: 0.54em, fit_height: none, preferred_width: none, weight: \"regular\", first_line_indent: 0pt, justify: false, eps: 0.08pt, bound_edges: false) = {",
        "  layout(size => {",
        "    let allowed-height = if fit_height == none { size.height } else { calc.min(size.height, fit_height) }",
        "    let render-width(text_size, leading, width) = if bound_edges { pdftr_glyph_block(markdown, text_size, weight: weight, leading: leading, width: width, first_line_indent: first_line_indent, justify: justify) } else { block(width: width)[#{",
        "      set text(size: text_size, weight: weight)",
        "      set par(leading: leading, justify: justify)",
        "      if first_line_indent > 0pt { h(first_line_indent) }",
        "      cmarker.render(markdown, math: mitex)",
        "    }] }",
        "    let fits-width(text_size, leading, width) = measure(width: width, render-width(text_size, leading, width)).height <= allowed-height",
        "    let width = size.width",
        "    let render(text_size, leading) = render-width(text_size, leading, pdftr_preferred_width(preferred_width, width, width => fits-width(text_size, leading, width)))",
        "    let fits(text_size, leading) = fits-width(text_size, leading, width)",
        "    if fits(max_size, max_leading) {",
        "      render(max_size, max_leading)",
        "    } else {",
        "      if fits(min_size, min_leading) {",
        "        let chosen-size = pdftr_fit_size(min_size, max_size, eps, size_pt => fits(size_pt, min_leading))",
        "        render(chosen-size, min_leading)",
        "      } else {",
        # The legacy frame ends at the baseline. Include glyph edges only for
        # paragraphs that already failed at their preferred minimum size.
        '        let emergency-render(text_size, width) = text(top-edge: "ascender", bottom-edge: "descender", render-width(text_size, min_leading, width))',
        "        let emergency-fits(text_size) = measure(width: width, emergency-render(text_size, width)).height <= allowed-height",
        "        let emergency-min-size = calc.min(min_size, calc.max(4.2pt, min_size * 0.65))",
        "        let emergency-size = pdftr_fit_size(emergency-min-size, min_size, eps, emergency-fits)",
        "        let final-width = pdftr_preferred_width(preferred_width, width, width => measure(width: width, emergency-render(emergency-size, width)).height <= allowed-height)",
        "        emergency-render(emergency-size, final-width)",
        "      }",
        "    }",
        "  })",
        "}",
        *flow_text_fit_helpers(),
    ]


def render_block_fit_helpers() -> list[str]:
    return [
        *glyph_edge_fit_helpers(),
        "#let pdftr_fit_size(lo, hi, eps, fits) = {",
        "  if hi - lo <= eps {",
        "    lo",
        "  } else {",
        "    let mid = lo + (hi - lo) / 2",
        "    if fits(mid) {",
        "      pdftr_fit_size(mid, hi, eps, fits)",
        "    } else {",
        "      pdftr_fit_size(lo, mid, eps, fits)",
        "    }",
        "  }",
        "}",
        "#let pdftr_fit_leading(lo, hi, eps, fits) = {",
        "  if hi - lo <= eps {",
        "    lo",
        "  } else {",
        "    let mid = lo + (hi - lo) / 2",
        "    if fits(mid) {",
        "      pdftr_fit_leading(mid, hi, eps, fits)",
        "    } else {",
        "      pdftr_fit_leading(lo, mid, eps, fits)",
        "    }",
        "  }",
        "}",
        "#let pdftr_floor_size(value, floor) = if value < floor { floor } else { value }",
        "#let pdftr_floor_leading(value, floor) = if value < floor { floor } else { value }",
        *preferred_width_helpers(),
        *single_line_fit_helpers(),
        '#let pdftr_fit_markdown(markdown, max_size: 10pt, min_size: 9pt, max_leading: 0.66em, min_leading: 0.54em, fit_height: none, preferred_width: none, weight: "regular", first_line_indent: 0pt, justify: false, eps: 0.08pt, bound_edges: false) = {',
        "  layout(size => {",
        "    let allowed-height = if fit_height == none { size.height } else { calc.min(size.height, fit_height) }",
        "    let render-width(text_size, leading, width) = if bound_edges { pdftr_glyph_block(markdown, text_size, weight: weight, leading: leading, width: width, first_line_indent: first_line_indent, justify: justify) } else { block(width: width)[#{",
        "      set text(size: text_size, weight: weight)",
        "      set par(leading: leading, justify: justify)",
        "      if first_line_indent > 0pt { h(first_line_indent) }",
        "      cmarker.render(markdown, math: mitex)",
        "    }] }",
        "    let fits-width(text_size, leading, width) = measure(width: width, render-width(text_size, leading, width)).height <= allowed-height",
        "    let width = size.width",
        "    let render(text_size, leading) = render-width(text_size, leading, pdftr_preferred_width(preferred_width, width, width => fits-width(text_size, leading, width)))",
        "    let fits(text_size, leading) = fits-width(text_size, leading, width)",
        "    if fits(max_size, max_leading) {",
        "      render(max_size, max_leading)",
        "    } else {",
        "      let fallback_min_size = min_size",
        "      let fallback_min_leading = min_leading",
        "      let emergency_min_size = calc.max(4.2pt, min_size * 0.65)",
        "      let emergency_min_leading = calc.max(0.20em, min_leading * 0.75)",
        "      let chosen_leading = if fits(min_size, max_leading) { max_leading } else { min_leading }",
        "      let chosen_size = if not fits(min_size, chosen_leading) {",
        "        let fallback_leading = fallback_min_leading",
        "        let emergency_leading = emergency_min_leading",
        "        if not fits(fallback_min_size, fallback_leading) {",
        "          pdftr_fit_size(emergency_min_size, fallback_min_size, eps, size_pt => fits(size_pt, emergency_leading))",
        "        } else {",
        "          pdftr_fit_size(fallback_min_size, min_size, eps, size_pt => fits(size_pt, fallback_leading))",
        "        }",
        "      } else {",
        "        pdftr_fit_size(min_size, max_size, eps, size_pt => fits(size_pt, chosen_leading))",
        "      }",
        "      let leading_floor = if fits(chosen_size, min_leading) { min_leading } else if fits(chosen_size, emergency_min_leading) { emergency_min_leading } else { emergency_min_leading }",
        "      let leading_cap = if fits(chosen_size, max_leading) { max_leading } else { chosen_leading }",
        "      let final_leading = if fits(chosen_size, leading_cap) {",
        "        leading_cap",
        "      } else {",
        "        pdftr_fit_leading(leading_floor, leading_cap, 0.01em, leading => fits(chosen_size, leading))",
        "      }",
        "      render(chosen_size, final_leading)",
        "    }",
        "  })",
        "}",
        *flow_text_fit_helpers(),
    ]


